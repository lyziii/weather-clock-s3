import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import jpeg from 'jpeg-js';

const [source, destination, preview] = process.argv.slice(2);
assert(source && destination, 'Usage: node generate_cyber_assets.mjs reference_directory_or_jpeg_c output.c');
const names = Array.from({ length: 10 }, (_, index) => `i${index}`);
const sourceCode = fs.statSync(source).isFile() ? fs.readFileSync(source, 'utf8') : null;
const previewData = preview ? Buffer.alloc(700 * 210 * 4, 255) : null;
const output = ['/* Generated by tools/generate_cyber_assets.mjs; upstream license: third_party/cyber_os/LICENSE. */',
    '#include "cyber_assets.h"', ''];

function jpegSize(bytes) {
    assert.equal(bytes.readUInt16BE(0), 0xffd8, 'Expected JPEG SOI');
    assert.equal(bytes.readUInt16BE(bytes.length - 2), 0xffd9, 'Expected JPEG EOI');
    let offset = 2;
    while (offset + 4 < bytes.length) {
        assert.equal(bytes[offset++], 0xff);
        while (bytes[offset] === 0xff) offset++;
        const marker = bytes[offset++];
        const length = bytes.readUInt16BE(offset);
        assert(length >= 2 && offset + length <= bytes.length, 'Invalid JPEG segment');
        if (marker === 0xc0) {
            assert.equal(bytes[offset + 2], 8, 'Expected baseline 8-bit JPEG');
            return { width: bytes.readUInt16BE(offset + 5), height: bytes.readUInt16BE(offset + 3) };
        }
        assert.notEqual(marker, 0xc2, 'Progressive JPEG is unsupported by TJPGD');
        offset += length;
    }
    throw new Error('Missing JPEG frame header');
}

for (const [frameIndex, name] of names.entries()) {
    const header = sourceCode
        ? sourceCode.match(new RegExp(`static const uint8_t ${name}_bytes\\[\\] = \\{([\\s\\S]*?)\\};`))?.[0]
        : fs.readFileSync(path.join(source, `${name}.h`), 'utf8');
    assert(header, `Missing JPEG source for ${name}`);
    const body = header.slice(header.indexOf('{') + 1, header.lastIndexOf('}'));
    const bytes = Buffer.from([...body.matchAll(/0x([0-9a-f]{2})\b/gi)].map(match => parseInt(match[1], 16)));
    const { width, height } = jpegSize(bytes);
    assert(width === 70 && height === 70, 'Astronaut frames must remain 70x70');
    const decoded = jpeg.decode(bytes, { useTArray: true, maxMemoryUsageInMB: 16 });
    const alpha = Buffer.alloc(width * height);
    // 去掉白底和 JPEG 浅色噪点，只保留带抗锯齿的深色线条。
    for (let pixel = 0; pixel < alpha.length; pixel++) {
        const offset = pixel * 4;
        const luminance = (77 * decoded.data[offset] + 150 * decoded.data[offset + 1] +
            29 * decoded.data[offset + 2]) / 256;
        alpha[pixel] = Math.round(Math.max(0, 243 - luminance) * 255 / 243);
    }
    assert(alpha.some(value => value > 128), `Empty astronaut mask: ${name}`);
    for (const corner of [0, width - 1, (height - 1) * width, width * height - 1]) {
        assert.equal(alpha[corner], 0, `JPEG corner must become transparent: ${name}`);
    }
    // 可选预览从上到下为原图、黑底白线和白底黑线，便于逐帧核对细节。
    if (previewData) {
        for (let pixel = 0; pixel < alpha.length; pixel++) {
            const column = frameIndex * width + pixel % width;
            const row = Math.floor(pixel / width);
            for (let channel = 0; channel < 3; channel++) {
                previewData[(row * 700 + column) * 4 + channel] = decoded.data[pixel * 4 + channel];
                previewData[((row + height) * 700 + column) * 4 + channel] = alpha[pixel];
                previewData[((row + height * 2) * 700 + column) * 4 + channel] = 255 - alpha[pixel];
            }
        }
    }
    output.push(`static const uint8_t ${name}_bytes[] = {`);
    for (let offset = 0; offset < alpha.length; offset += 16) {
        output.push('    ' + [...alpha.subarray(offset, offset + 16)].map(value => `0x${value.toString(16).padStart(2, '0')}`).join(',') + ',');
    }
    output.push('};', `static const lv_image_dsc_t cyber_${name} = {`,
        `    .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_A8, .w = ${width}, .h = ${height}, .stride = ${width}},`,
        `    .data_size = sizeof(${name}_bytes), .data = ${name}_bytes,`, '};', '');
    console.log(`${name}: ${width}x${height}, ${bytes.length} JPEG bytes -> ${alpha.length} alpha bytes`);
}
output.push('const void *cyber_animation[10] = {',
    '    ' + Array.from({ length: 10 }, (_, index) => `&cyber_i${index}`).join(', ') + ',', '};', '');
fs.writeFileSync(destination, output.join('\n'));
if (previewData) {
    fs.writeFileSync(preview, jpeg.encode({ data: previewData, width: 700, height: 210 }, 95).data);
}